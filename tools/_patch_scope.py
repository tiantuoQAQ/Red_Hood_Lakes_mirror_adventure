# 收缩角色范围到 5 人，并同步三份文档
import io, re

ROOT = r'E:\UserDATAxtmr\Documents\DSH\mirror-jam\docs'

KEEP = {'2.1', '2.2', '2.4', '2.5', '2.9'}   # 蕾克 / 诺登 / 猩红魔姬 / 玛丽苏 / 梅贝尔


def read(name):
    return io.open(ROOT + '\\' + name, encoding='utf-8').read()


def write(name, text):
    io.open(ROOT + '\\' + name, 'w', encoding='utf-8', newline='\n').write(text)


# ---------------------------------------------------------------- 即梦文档
name = '即梦出图提示词.md'
t = read(name)

# 1) 顶部加范围说明
t = t.replace(
    '> 图 14–16 只当**构图、角色大小、姿态**参考，**不要复制里面的角色形象与配色**。',
    '''> 图 14–16 只当**构图、角色大小、姿态**参考，**不要复制里面的角色形象与配色**。
>
> **⚠️ 角色范围已收缩到 5 人**（时间不够，砍掉其余角色）：
> 小红帽蕾克、猩红魔姬蕾克、玛丽苏、白之兔诺登、虚空少女梅贝尔。
> 其中**猩红魔姬由脚本从蕾克派生，不用即梦画**。所以即梦实际只需要画 4 个角色 × 3 层 + 1 个光球。''',
    1)

# 2) 图号表里标注哪些图不用了
for fig, note in [
    ('图4', 'Q 版四人插画：青蛙帽红裙、蓝发人鱼尾、银发大红结蓝裙、银发皇冠白礼服'),
    ('图5', '**青蛙姬** 插画：绿发双马尾、精灵耳、白色女仆头饰、蓝蝴蝶结、绿色叶状翅膀、绿色连体衣'),
    ('图7', '青蛙姬 惊恐表情（同图5角色）'),
    ('图8', '四人插画：蓝发红结黑裙、粉发黑玫瑰红黑裙、白发兔耳白裙持匕首、金发红兽耳白毛兜帽持匕首'),
    ('图11', '**紫发角色**：紫发紫眼、红色大蝴蝶结、白色兽耳、黑红连衣裙'),
]:
    t = t.replace('| ' + fig + ' | ' + note + ' | 只取单个角色，勿画群像 |',
                  '| ' + fig + ' | ' + note + ' | ~~不用（角色已砍）~~ |')
    t = t.replace('| ' + fig + ' | ' + note + ' | 造型参考 |',
                  '| ' + fig + ' | ' + note + ' | ~~不用（角色已砍）~~ |')
    t = t.replace('| ' + fig + ' | ' + note + ' | 表情参考 |',
                  '| ' + fig + ' | ' + note + ' | ~~不用（角色已砍）~~ |')
    t = t.replace('| ' + fig + ' | ' + note + ' | ⚠️ 待你确认是谁 |',
                  '| ' + fig + ' | ' + note + ' | ~~不用（角色已砍）~~ |')

# 3) 删掉被砍角色的提示词段落（2.3 人鱼姬 / 2.6 青蛙姬 / 2.7 长发姬 / 2.8 白雪姬）
blocks = re.split(r'(?=^### 2\.\d )', t, flags=re.M)
out = []
for b in blocks:
    m = re.match(r'^### (2\.\d) ', b)
    if m:
        if m.group(1) in KEEP:
            out.append(b)
        # else: 丢弃
    else:
        out.append(b)
t = ''.join(out)

# 4) 段落重新编号为 2.1 ~ 2.5
order = ['2.1', '2.2', '2.4', '2.5', '2.9']
for i, old in enumerate(order):
    t = t.replace('### ' + old + ' ', '### 2.%d ' % (i + 1), 1)

# 5) 修正交叉引用
t = t.replace('用 2.1 的完整提示词', '用 2.1（蕾克）的完整提示词')
write(name, t)
print('%s: 保留 %d 个角色' % (name, len(order)))

